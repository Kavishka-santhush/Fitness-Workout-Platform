function parse() {
  return ROWS.filter(Boolean).map((row, i) => {
    const [name, exerciseType, category, primary, equipment, difficulty, met] = row.split('|');
    return {
      key: 'ex-' + i,
      name: name.trim(),
      description: `${category} ${exerciseType.toLowerCase()} movement primarily targeting the ${primary.toLowerCase()}, performed with ${equipment.toLowerCase()}.`,
      exerciseType,
      difficulty,
      category,
      primaryMuscles: [primary],
      secondaryMuscles: [],
      equipment: equipment === 'Bodyweight' ? ['No Equipment', 'Bodyweight'] : [equipment],
      metValue: met ? Number(met) : null,
      instructions: [
        { step: 1, text: `Set up in the starting position for ${name.trim()}.` },
        { step: 2, text: 'Brace your core and execute the movement with controlled form.' },
        { step: 3, text: 'Complete the prescribed reps, then return to the start under control.' },
      ],
      tips: ['Maintain a neutral spine throughout.', 'Breathe out on exertion.'],
      commonMistakes: ['Using momentum instead of control.', 'Going too heavy too soon.'],
      variations: { beginner: [], advanced: [], equipment: [] },
      status: 'APPROVED',
      isCommunity: false,
    };
  });
}

